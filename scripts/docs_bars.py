"""Write the brand's dotted bars into docs/style.css as data URIs.

Same anatomy as the landing page's MiniBar: 10 cells long and 2 thick, sparse
dots (4 cells), then a checkerboard (4), then a solid end (2). Data URIs, not
files, because the docs are served under /docs and a root path would miss.

    python3 scripts/docs_bars.py
"""

import re
from pathlib import Path
from urllib.parse import quote

STYLE = Path(__file__).resolve().parent.parent / "docs" / "style.css"
COLORS = {"dark": "#3FD3DE", "light": "#0FA3B1"}


def bar(color: str, cell: int = 2, vertical: bool = False) -> str:
    half = max(cell // 2, 1)
    rects = []
    for i in range(10):
        for j in range(2):
            x, y = i * cell, j * cell
            if i < 4:
                rects.append((x + half, y, half, half))
            elif i < 8:
                rects += [(x + half, y, half, half), (x, y + half, half, half)]
            else:
                rects.append((x, y, cell, cell))
    width, height = 10 * cell, 2 * cell
    if vertical:  # a column: solid end at the top, sparse dots at the bottom
        rects = [(y, width - x - w, h, w) for x, y, w, h in rects]
        width, height = height, width
    body = "".join(f"<rect x='{x}' y='{y}' width='{w}' height='{h}'/>" for x, y, w, h in rects)
    svg = (f"<svg xmlns='http://www.w3.org/2000/svg' width='{width}' height='{height}' "
           f"fill='{color}' shape-rendering='crispEdges'>{body}</svg>")
    return f'url("data:image/svg+xml,{quote(svg, safe=" =:/<>")}")'


def main() -> None:
    lines = []
    for scheme, color in COLORS.items():
        lines.append(f"  --ps-bar-{scheme}: {bar(color)};")
        lines.append(f"  --ps-col-{scheme}: {bar(color, vertical=True)};")
    block = "/* bars:start (generated by scripts/docs_bars.py) */\n" + "\n".join(lines) + "\n  /* bars:end */"
    css = STYLE.read_text()
    css, count = re.subn(r"/\* bars:start.*?bars:end \*/", block, css, flags=re.S)
    if count != 1:
        raise SystemExit("style.css needs one bars:start … bars:end block")
    STYLE.write_text(css)
    print(f"wrote {len(lines)} bars into {STYLE.name}")


if __name__ == "__main__":
    main()
